import { MCP } from "./site";

export const LEXLEAN_SKILL_NAME = MCP.skill;
export const LEXLEAN_SKILL_DESCRIPTION =
  `Write LexLean specifications through the public LexLean MCP server (${MCP.url}) to write a draft, check it, read the diagnostics, fix, verify in Lean, and present the signed result. Use when a task asks for a LexLean spec, a .lex.tex module, a formally verified specification, or mentions lexlean-mcp or mcp.uor.foundation. No account or token is needed.`;
/** The lexlean-mcp commit the endpoint ran, and the day the steps below were checked against it. */
export const VERIFIED_ON = "2026-11-04";
export const VERIFIED_WITH = "lexlean-mcp 6abea22 (serverInfo 0.1.0)";
export const LEXLEAN_ISSUES = "https://github.com/UOR-Foundation/lexlean-mcp/issues";
export const LEXLEAN_LANGUAGE_ISSUES = "https://github.com/UOR-Foundation/LexLean/issues";

/** A module that checks and verifies on the `spec` profile, as the skill shows it. */
export const MINIMAL_MODULE = [
  "\\begin{lexlean}{Main}",
  "\\useglossary{lexlean.std.nat@1.2.0}",
  "\\title{addition}",
  "\\begin{semanticmodule}",
  "definition{",
  "  name: double,",
  "  parameters: [value : Nat],",
  "  result: Nat,",
  "  body: (value + value),",
  "  executable: true",
  "}",
  "\\end{semanticmodule}",
  "\\end{lexlean}",
].join("\n");

export const CLIENT_CONFIG = `{ "mcpServers": { "lexlean": { "type": "http", "url": "${MCP.url}" } } }`;

export function lexleanSkillMarkdown() {
  return [
    "---",
    `name: ${LEXLEAN_SKILL_NAME}`,
    `description: "${LEXLEAN_SKILL_DESCRIPTION}"`,
    "---",
    "",
    "# LexLean MCP",
    "",
    "LexLean turns a precise English specification into a module that a machine checks, proves in Lean, signs and renders. The LexLean MCP server gives an agent that whole loop as tools: every mistake comes back as an exact diagnostic, and a finished spec comes back with a signed attestation anyone can check offline.",
    "",
    "## Connect",
    "",
    `The server is public at ${MCP.url} (Streamable HTTP, POST). No token, no account. Any MCP client works: the usual \`initialize\` handshake, or MCP revision \`2026-07-28\` with \`_meta\` on each request.`,
    "",
    "```json",
    CLIENT_CONFIG,
    "```",
    "",
    "Limits per client: 240 requests a minute, 6 verifications a minute, 9 MiB a request. Past a limit the answer is 429 with `Retry-After`; wait that long. The server's `initialize` result carries these steps as `instructions`.",
    "",
    "## 1. Pick a profile",
    "",
    "A profile is the project a draft is checked in: its language, its source roots and its vocabulary. `lexlean_profiles {}` lists them. Today there is one, `spec`: language 1.2, with `lexlean.core`, `lexlean.std.nat` and `lexlean.std.bool`. A spec that needs another vocabulary (such as `prism.arch`) cannot be checked until a profile holds it; say so to the user instead of guessing.",
    "",
    "## 2. Find the words before you write",
    "",
    "A LexLean module is written in the vocabulary of its profile. A word outside it is an error, titles included.",
    "",
    "- `lexlean_lexicon_search {\"profile\": \"spec\", \"query\": \"natural\"}` returns entries with their surface forms. Page with `offset` and `limit`.",
    "- `lexlean_lexicon_read {\"profile\": \"spec\", \"entry\": \"<id>\"}` reads one entry.",
    "- Declare each package you use: `\\useglossary{lexlean.std.nat@1.2.0}`.",
    "",
    "## 3. Write a draft",
    "",
    "```json",
    "lexlean_draft_write {\"profile\": \"spec\", \"files\": [{\"path\": \"src/Main.lex.tex\", \"content\": \"...\"}]}",
    "```",
    "",
    "The answer names the draft: `{\"draft\": \"spec/<64 hex>\", ...}`. A draft is immutable; every write gives a new handle. Use the newest one. A draft may replace a file the profile holds, `src/Main.lex.tex` included. Paths must lie under `src/` and end in `.lex.tex`.",
    "",
    "Rules that save a round trip:",
    "",
    "- **The module name is the file name.** `src/Main.lex.tex` starts with `\\begin{lexlean}{Main}`. A mismatch is `LLP2003`.",
    "- **The title is a vocabulary phrase.** `\\title{addition}` works; `\\title{Spec}` is `LLL1004 ... is not a phrase concept`.",
    "",
    "A minimal module that checks and verifies:",
    "",
    "```latex",
    MINIMAL_MODULE,
    "```",
    "",
    "## 4. Check, read, fix",
    "",
    "```json",
    "lexlean_check {\"project\": \"spec/<id>\"}",
    "```",
    "",
    "- The result is exactly what `lexlean check --diagnostic-format json` prints. `success: true` and `exit_code: 0` mean the draft is clean.",
    "- Each diagnostic has a `code`, a `message` and a `primary` span (path, line, column). **The message is the fix**: `phase link: unbound local 'vaule'` names the typo.",
    "- `lexlean_explain {\"code\": \"LLT4001\"}` gives the class of the code. Use it when the message alone is not enough.",
    "- Fix by writing a new draft, then check again. `lexlean_format` (with `check_only`) and `lexlean_snapshot` are there when you need them.",
    "",
    "## 5. Verify",
    "",
    "Verification runs the proof in Lean. It took 15 to 35 seconds for the module above.",
    "",
    "```json",
    "lexlean_verify {\"project\": \"spec/<id>\"}",
    "```",
    "",
    "- With the tasks extension in your `clientCapabilities`, you get `{\"taskId\": ..., \"status\": \"working\"}`; poll `tasks/get` until the status is not `working`.",
    "- Otherwise you get `{\"task\": \"task-N\", \"state\": \"running\"}`; poll `lexlean_verify_control {\"task\": \"task-N\", \"action\": \"status\"}` until `state` is not `running`. `action: \"cancel\"` stops it.",
    "- When verified, the result text holds `attestation_id`, `build_id`, `semantic_id` and `source_id`. A failed verification carries the same diagnostics as a check.",
    "",
    "## 6. Present and share",
    "",
    "- `lexlean_present {\"by\": \"id\", \"value\": \"<attestation_id>\"}` returns the attested canonical LaTeX as an embedded resource, with its signed envelope. Show this to the user: it is the spec as verified.",
    "- `lexlean_attestation {\"by\": \"id\", \"value\": \"<attestation_id>\"}` looks the record up. `by: \"digest\"` takes the SHA-256 of a source file instead.",
    "- `lexlean_export {\"by\": \"id\", \"value\": \"<attestation_id>\"}` writes a bundle a reader checks offline.",
    "",
    "## Failures",
    "",
    "| Answer | Meaning | Do |",
    "| --- | --- | --- |",
    "| `{\"failure\": \"project-refused\"}` | The draft or profile is absent or changed, or a draft file sits where the profile has a directory | Use the handle `lexlean_draft_write` returned |",
    "| `{\"refusal\": \"DraftUnknown\"}` | No such draft | Same |",
    "| `{\"failure\": \"engine-unavailable\"}` or `{\"failure\": \"verifier-unavailable\"}` | A service of the server is down | Tell the user; do not retry in a loop |",
    "| `{\"failure\": \"verifier-lost\"}` | The verifier stopped during the task | Verify again once |",
    "| HTTP 429 | A rate limit | Wait `Retry-After` seconds |",
    "| HTTP 400, `-32602` | Missing `_meta` (2026-07-28 clients), or an unknown tool | Fix the request |",
    "",
    "## Not here",
    "",
    "The server stops at a verified, signed LexLean module. It does not build a Prism app from it; that is `prism build` (Prism SDK). Everyone shares one store: drafts are addressed by the hash of their content and are not listed, but do not put secrets in one.",
    "",
    "## When something fails",
    "",
    `- The server does something other than this file says: ${LEXLEAN_ISSUES}`,
    `- The language or a diagnostic is wrong: ${LEXLEAN_LANGUAGE_ISSUES}`,
    "",
    `Steps verified against ${VERIFIED_WITH} on ${VERIFIED_ON}.`,
    "",
  ].join("\n");
}
